import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const base = 'http://127.0.0.1:8090';
const key = readFileSync('C:/m3u-player/proxy-key.txt', 'utf8').trim();
const pl = JSON.parse(readFileSync('C:/m3u-player/data/shotfix.json', 'utf8'));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await ctx.route(/\/(live|movie|series|timeshift)\/|\/hls[?/]|\/hls$|\.ts(\?|$)|\.m3u8|\/sync/, r => r.abort());
const page = await ctx.newPage();
await page.goto(`${base}/index.html`); await page.waitForTimeout(1500);
await page.evaluate(async ({ pl, key }) => { const { db } = await import('/js/db.js'); await db.putPlaylist(pl); const s = (await db.get('settings')) || {}; await db.set('settings', { ...s, serverKey: key }); }, { pl, key });
await page.reload(); await page.waitForTimeout(8000);
await page.evaluate(() => { location.hash = '#/movies'; }); await page.waitForTimeout(4000);
await page.evaluate(() => scrollTo(0, document.body.scrollHeight)); await page.waitForTimeout(1500);
console.log('movies scrolled to', await page.evaluate(() => Math.round(scrollY)));
await page.click('#mainnav [data-nav="series"]'); await page.waitForTimeout(3000);
console.log('series opened at', await page.evaluate(() => Math.round(scrollY)), 'tab', await page.evaluate(() => document.querySelector('#mainnav .on')?.dataset.nav));
await page.click('#mainnav [data-nav="movies"]'); await page.waitForTimeout(3000);
console.log('movies again at', await page.evaluate(() => Math.round(scrollY)));
await browser.close();
