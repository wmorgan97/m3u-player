import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const base = 'http://127.0.0.1:8090';
const key = readFileSync('C:/m3u-player/proxy-key.txt', 'utf8').trim();
const pl = JSON.parse(readFileSync('C:/m3u-player/data/shotfix.json', 'utf8'));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1512, height: 945 } });
await ctx.route(/\/(live|movie|series|timeshift)\/|\/hls[?/]|\/hls$|\.ts(\?|$)|\.m3u8|\/sync/, r => r.abort());
const page = await ctx.newPage();
page.on('pageerror', e => console.log('pageerror', e.message));
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log('console', m.text().slice(0, 200)); });
await page.goto(`${base}/index.html`);
await page.waitForTimeout(1500);
await page.evaluate(async ({ pl, key }) => { const { db } = await import('/js/db.js'); await db.putPlaylist(pl); const s = (await db.get('settings')) || {}; await db.set('settings', { ...s, serverKey: key }); }, { pl, key });
await page.reload();
await page.waitForTimeout(5000);
console.log('direct:', await page.evaluate(async ({ pl, key }) => {
  const r = await fetch(`/vod?key=${encodeURIComponent(key)}`, { method: 'POST', body: JSON.stringify({ server: pl.xtream.server, user: pl.xtream.user, pass: pl.xtream.pass, kind: 'movies', versions: 'EN - Inception  (2010)' }) });
  const d = await r.json(); return r.status + ' ' + (d.items || []).map(i => i.name + ' cat=' + i.category_id).join(' | ');
}, { pl, key }));
await page.fill('#tq', 'Inception');
await page.waitForTimeout(4000);
console.log('results:', await page.evaluate(() => [...document.querySelectorAll('#ts-results .hs-row .row-name')].map(x => x.textContent).slice(0, 6).join(' | ')));
await page.evaluate(() => [...document.querySelectorAll('#ts-results .hs-row')].find(r => /^Inception/.test(r.querySelector('.row-name')?.textContent || '') && r.dataset.shelf === 'hs-movie')?.click());
await page.waitForTimeout(4000);
console.log('sheet:', await page.evaluate(() => document.querySelector('#sheet .detail-title')?.textContent + ' | banner: ' + (document.querySelector('#sheet .vbanner')?.textContent || 'none')));
await page.evaluate(() => document.querySelector('#sheet [data-play]')?.click());
await page.waitForTimeout(3000);
console.log('after play:', await page.evaluate(() => (document.querySelector('#sheet .sheet-title')?.textContent || 'no sheet') + ' | rows: ' + [...document.querySelectorAll('.vrow b')].map(b => b.textContent).join(' / ') + ' | playing=' + document.body.classList.contains('playing')));
await browser.close();
