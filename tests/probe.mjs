import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const base = 'http://127.0.0.1:8090';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1512, height: 945 } });
await ctx.route(/\/(live|movie|series|timeshift)\/|\/hls[?/]|\/hls$|\.ts(\?|$)|\.m3u8/, r => r.abort());
const page = await ctx.newPage();
page.on('pageerror', e => console.log('pageerror', e.message));
const key = readFileSync('C:/m3u-player/proxy-key.txt', 'utf8').trim();
const pl = JSON.parse(readFileSync('C:/m3u-player/data/shotfix.json', 'utf8'));
await page.goto(`${base}/index.html`);
await page.waitForTimeout(1500);
await page.evaluate(async ({ pl, key }) => { const { db } = await import('/js/db.js'); await db.putPlaylist(pl); const s = (await db.get('settings')) || {}; await db.set('settings', { ...s, serverKey: key }); }, { pl, key });
await page.goto('about:blank');
await page.goto(`${base}/index.html#/series`);
await page.waitForTimeout(800);
console.log('after load:', await page.evaluate(() => location.hash));
await page.waitForTimeout(9000);
console.log('state:', await page.evaluate(() => location.hash + ' | ' + document.querySelector('#list')?.className + ' | ' + document.querySelector('#title')?.textContent + ' | ' + document.querySelectorAll('#list > li').length));
console.log('hero:', await page.evaluate(() => [...document.querySelectorAll('.hero-kicker')].map(k => k.textContent.trim()).join(' | ')));
console.log('series shelves:', await page.evaluate(() => [...document.querySelectorAll('#list .shelf-head h3')].slice(0, 8).map(h => h.textContent).join(' | ')));
await page.evaluate(() => { location.hash = '#/movies'; });
await page.waitForTimeout(6000);
const n = await page.evaluate(() => { const c = [...document.querySelectorAll('#chips .chip')].find(c => /^Action\d/.test(c.textContent)); if (!c) return 'no chip'; c.click(); return c.outerHTML.slice(0, 160); });
console.log('clicked:', n);
await page.waitForTimeout(500);
console.log('after click:', await page.evaluate(() => document.querySelector('#chips .chip.active')?.textContent + ' | list ' + document.querySelector('#list')?.className + ' ' + document.querySelectorAll('#list > li').length));
await page.waitForTimeout(8000);
console.log('chips:', await page.evaluate(() => [...document.querySelectorAll('#chips .chip')].slice(0, 8).map(c => c.textContent).join(' | ')));
console.log('action:', await page.evaluate(() => document.querySelector('.lib-head h2')?.textContent + ' / ' + document.querySelectorAll('#list .poster').length + ' posters / first: ' + [...document.querySelectorAll('#list .poster .poster-name')].slice(0, 5).map(x => x.textContent).join(', ')));
await page.screenshot({ path: 'C:/m3u-player/data/shots/desk-action.png' });
await browser.close();
